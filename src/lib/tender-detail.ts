import type { Tender } from "./demo-data";

export type DetailDocument = {
  name: string;
  kind: string;
  facts: readonly string[];
  sources: readonly string[];
  text: string;
};
export type PartSpec = {
  code: string;
  brand: string;
  name: string;
  qty: number;
  match: string;
  status: string;
};
export type DetailFlow = {
  parts: readonly PartSpec[];
  technical: string[][];
  documents: readonly DetailDocument[];
  summary: string;
  checks: string;
  requirements: string[];
  risks: string[];
  plan: string[];
  delivery: string;
};

// Only the filter showcase uses its extracted catalogue and document fixtures.
export function detailFlow(
  t: Tender,
  filterParts: readonly PartSpec[],
  filterDocs: readonly DetailDocument[],
): DetailFlow {
  if (
    t.topCategory === "Запчастини" &&
    t.id.replace(/-IMP.*$/, "") === "UA-2026-08-25-006722-a"
  )
    return {
      parts: filterParts,
      technical: [],
      documents: filterDocs,
      summary:
        "Релевантна товарна група та точні каталожні номери. Перевірити аналоги, авторизаційний лист і вимоги до документів.",
      checks:
        "Підтвердити сумісність LF9009 / FS19532 та аналогів, перевірити авторизаційний лист.",
      requirements: [
        "2 аналогічні договори",
        "Фінансова звітність",
        "Авторизаційний лист виробника",
        "Підтвердження сумісності аналогів",
        "Гарантія 12 міс",
        "Поставка до 30 днів",
      ],
      risks: [
        "Аналоги потребують підтвердження сумісності",
        "Авторизаційний лист виробника",
        "Штраф за прострочення (демо)",
        "Валютний курс імпортних позицій",
      ],
      plan: [
        "Перевірити каталожні номери та аналоги",
        "Запросити підтвердження сумісності",
        "Підготувати аналогічні договори",
        "Перевірити гарантійні вимоги",
        "Отримати закупівельні ціни",
        "Порахувати маржу",
      ],
      delivery: "До 30 календарних днів",
    };
  const crane = t.title.includes("Автокран");
  const dump = t.title.includes("Самоскиди");
  const equipment = t.topCategory === "Техніка";
  const delivery = crane ? "До 90 днів" : "Уточнити за технічним завданням";
  const technical = crane
    ? [
        ["Тип", "Автокран"],
        ["Модель", "XCMG QY25K5 або еквівалент"],
        ["Кількість", "2 од."],
        ["Вантажопідйомність", "25 т"],
        ["Колісна формула", "6×4"],
        ["Максимальна висота підйому", "~47 м"],
        ["Основна стріла", "~39 м"],
        ["Двигун / потужність", "Підтвердити за паспортом виробника"],
        ["Гарантія", "12 міс"],
        ["Строк поставки", delivery],
      ]
    : dump
      ? [
          ["Тип", "Самоскид"],
          ["Бренд", "DONGFENG"],
          ["Кількість", "4 од."],
          ...[
            "Колісна формула",
            "Вантажопідйомність",
            "Об’єм кузова",
            "Двигун / потужність",
            "КПП",
            "Екологічний стандарт",
            "Гарантія",
            "Строк поставки",
          ].map((label) => [label, "Уточнити за технічним завданням"]),
        ]
      : [
          ["Предмет", t.title],
          ["Категорія", t.category],
          ["Технічні параметри", "Потребують уточнення за документацією"],
          ["Строк поставки", delivery],
        ];
  const summary = crane
    ? "Висока відповідність профілю компанії. XCMG входить до цільового бренду, технічний клас відповідає асортименту. Перевірити строк постачання, гарантійні вимоги та підтвердження сервісного обслуговування."
    : dump
      ? "Предмет напряму відповідає основній діяльності компанії. Самоскиди DONGFENG — цільова вантажна техніка. Перевірити технічні параметри, гарантію та строк поставки."
      : t.recommendation;
  const checks = equipment
    ? "Перевірити строк поставки, сервісний центр, гарантію та сертифікацію / походження."
    : "Уточнити специфікацію, сумісність і вимоги до документів.";
  const requirements = equipment
    ? [
        "Таблиця технічної відповідності",
        "Паспорт та сертифікація техніки",
        "Підтвердження сервісного центру",
        crane ? "Гарантія 12 міс" : "Уточнити гарантійний строк",
        delivery,
        "Документи про походження",
      ]
    : [
        "Специфікація предмета закупівлі",
        "Документи про відповідність",
        "Уточнити кваліфікаційні вимоги",
      ];
  const risks = equipment
    ? [
        "Строк поставки",
        "Сервісний центр",
        "Гарантія",
        "Сертифікація / походження",
        "Валютний курс",
      ]
    : [
        "Повнота технічних вимог",
        "Підтвердження відповідності",
        "Строк поставки",
      ];
  const plan = equipment
    ? [
        "Підтвердити модель та технічні параметри",
        "Уточнити строк поставки",
        "Підтвердити сервісний центр",
        "Перевірити гарантію та сертифікацію",
        "Заповнити таблицю технічної відповідності",
        "Розрахувати ціну з урахуванням валютного курсу",
      ]
    : [
        "Уточнити специфікацію",
        "Перевірити документи про відповідність",
        "Розрахувати ціну",
        "Підготувати пропозицію",
      ];
  const documents = [
    "Технічне завдання.pdf",
    "Технічна специфікація.xlsx",
    "Проєкт договору.docx",
    "Кваліфікаційні вимоги.pdf",
    "Форма технічної відповідності.xlsx",
    "Гарантійні вимоги.pdf",
  ].map((name, i) => ({
    name,
    kind: name.endsWith(".xlsx") ? "technical" : "text",
    facts:
      i < 2
        ? technical.map(([label, value]) => `${label}: ${value}`)
        : i === 2
          ? [delivery, "Перевірити умови оплати та відповідальність"]
          : i === 3
            ? requirements
            : i === 4
              ? [t.title, "Підтвердити кожен технічний параметр менеджером"]
              : [
                  crane
                    ? "Гарантія 12 міс"
                    : "Гарантійний строк потребує уточнення",
                  "Підтвердження сервісного обслуговування",
                ],
    sources: ["Демонстраційний витяг — звірити з оригіналом"],
    text: `${t.title}\n${t.id}\n${i === 2 ? `Строк поставки: ${delivery}. Умови оплати та відповідальність потребують перевірки за оригіналом договору.` : i === 3 ? requirements.join("\n") : i === 5 ? requirements.filter((x) => /Гарантія|гарантійний|сервіс/i.test(x)).join("\n") : summary}`,
  }));
  return {
    parts: [],
    technical,
    documents,
    summary,
    checks,
    requirements,
    risks,
    plan,
    delivery,
  };
}
